#!/usr/bin/env python3
"""checks_to_notes.py SCORE_LY_DIR P1:B1-B2 P2:B1-B2 ...

Regenerate the "Readings to check" section of SCORE_LY_DIR/NOTES.md from the
`% CHECK` comments in SCORE_LY_DIR/music/*.ly. Each argument maps a manuscript
page to its bar range, e.g. 1:1-13 2:14-26.
Part names are taken from the instrumentName in instruments.ly.
"""
import collections, glob, os, re, sys

d = sys.argv[1]
pages = []
for a in sys.argv[2:]:
    p, r = a.split(":"); lo, hi = map(int, r.split("-")); pages.append((int(p), lo, hi))
names = {}
inst = open(os.path.join(d, "instruments.ly")).read()
for m in re.finditer(r'instrumentName = "([^"]+)".*?\\(\w+) \}', inst, re.S):
    names[m.group(2)] = m.group(1)
rows = collections.defaultdict(list)
for f in sorted(glob.glob(os.path.join(d, "music", "*.ly"))):
    var = re.search(r"^(\w+) = \{", open(f).read(), re.M).group(1)
    for line in open(f):
        m = re.search(r"% (\d+)\s+(.*CHECK.*)$", line)
        if not m:
            continue
        b = int(m.group(1))
        note = re.sub(r"\s*CHECK\s*", " ", m.group(2)).strip(" -()") or "uncertain reading"
        page = next((p for p, lo, hi in pages if lo <= b <= hi), 0)
        rows[page].append((b, names.get(var, var), note))
out = ["## Readings to check against the manuscript", "",
       "Generated by `tools/checks_to_notes.py` from the `% CHECK` comments in `music/*.ly`.", ""]
for p in sorted(rows):
    lo, hi = next(((lo, hi) for q, lo, hi in pages if q == p), (0, 0))
    out += [f"### Manuscript page {p} (bars {lo}–{hi})", ""]
    out += [f"- bar {b}, {n}: {note}" for b, n, note in sorted(rows[p])] + [""]
path = os.path.join(d, "NOTES.md")
head = open(path).read().split("## Readings to check")[0].rstrip() + "\n\n"
open(path, "w").write(head + "\n".join(out))
print(sum(len(v) for v in rows.values()), "CHECK items")
